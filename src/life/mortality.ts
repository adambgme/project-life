/**
 * The mortality model: from ONS mortality rates to a person's survival curve, life expectancy and the chance of
 * reaching any age. Pure functions over the bundled tables. It never produces a single "death date": only
 * probabilities, ranges and averages.
 */
import { ageOn, daysBetween, type CalendarDate } from './lifeMaths'

export type Sex = 'male' | 'female' | 'both'
export type Variant = 'principal' | 'high' | 'low'
/** Cohort: the death rates people born when you were are projected to meet as they age (ONS's improving rates).
 * Period: this year's death rates, held fixed for the rest of your life (the headline "life expectancy"). */
export type Basis = 'cohort' | 'period'

/** One nation's rates, as generated by scripts/data/build.ts. `rates[sex][variant][year - firstYear][age]` is qx
 * per 100,000 × `scale`. */
export type MortalityData = {
  nation: string
  source: { edition: string; released: string; title: string; url: string; attribution: string; licence: string }
  firstYear: number
  lastYear: number
  maxAge: number
  scale: number
  rates: Record<'male' | 'female', Record<Variant, number[][]>>
}

/** Follow survival to this age. Beyond the tables' last age (100), rates keep rising at the pace they rose from 99
 * to 100, which reproduces ONS's published life expectancy at 100 to within a few hundredths of a year. */
const LAST_AGE = 120

export type Outlook = {
  /** Completed years of age today: the curve starts here, given you're alive now. */
  fromAge: number
  /** `survival[k]`: chance of being alive at exact age `fromAge + k` (`survival[0]` is 1). */
  survival: number[]
  /** Average age at death for people like you who are alive at `fromAge`. */
  lifeExpectancy: number
}

export type OutlookOptions = { sex: Sex; variant?: Variant; basis?: Basis }

/** The probability (0–1) of dying between exact ages `age` and `age + 1` in a calendar year. */
export function deathRate(data: MortalityData, sex: Sex, variant: Variant, year: number, age: number): number {
  const y = Math.min(Math.max(year, data.firstYear), data.lastYear) - data.firstYear
  const table = (s: 'male' | 'female', a: number) => data.rates[s][variant][y]![a]! / data.scale / 100_000
  const rate = (s: 'male' | 'female') => {
    if (age <= data.maxAge) return table(s, age)
    const last = table(s, data.maxAge)
    return Math.min(1, last * (last / table(s, data.maxAge - 1)) ** (age - data.maxAge))
  }
  return sex === 'both' ? (rate('male') + rate('female')) / 2 : rate(sex)
}

/** Survival from a given age. Cohort follows the person's own calendar years; period holds `year` fixed. */
export function survivalFrom(
  data: MortalityData,
  { sex, variant = 'principal', basis = 'cohort' }: OutlookOptions,
  birthYear: number,
  fromAge: number,
  year: number,
): number[] {
  const survival = [1]
  for (let age = fromAge; age < LAST_AGE; age++) {
    const q = deathRate(data, sex, variant, basis === 'cohort' ? birthYear + age : year, age)
    survival.push(survival[survival.length - 1]! * (1 - q))
  }
  return survival
}

/** Expected further years of life from the curve's start: each later birthday reached, plus half a year. */
function expectedYears(survival: number[]): number {
  return survival.slice(1).reduce((sum, s) => sum + s, 0) + 0.5
}

/** A living person's outlook from today. */
export function outlook(data: MortalityData, birthDate: CalendarDate, today: CalendarDate, options: OutlookOptions): Outlook {
  const fromAge = Math.max(0, ageOn(birthDate, today))
  const survival = survivalFrom(data, options, birthDate.year, fromAge, today.year)
  return { fromAge, survival, lifeExpectancy: fromAge + expectedYears(survival) }
}

/** Chance (0–1) of being alive at an exact age, read from the curve (1 for ages already reached). */
export function chanceOfReaching(o: Outlook, age: number): number {
  const k = age - o.fromAge
  if (k <= 0) return 1
  const lower = Math.floor(k)
  const a = o.survival[lower] ?? 0
  const b = o.survival[lower + 1] ?? 0
  return a + (b - a) * (k - lower)
}

/** The age by which the chance of still being alive has fallen to `p` (e.g. 0.5: half of people like you live
 * beyond it). */
export function ageAtChance(o: Outlook, p: number): number {
  const s = o.survival
  for (let k = 0; k < s.length - 1; k++) {
    if (s[k + 1]! <= p) return o.fromAge + k + (s[k]! - p) / (s[k]! - s[k + 1]!)
  }
  return o.fromAge + s.length - 1
}

/** Life expectancy at birth for a birth year (ONS's headline cohort or period figure), for checking against ONS. */
export function lifeExpectancyAtBirth(data: MortalityData, options: OutlookOptions, birthYear: number): number {
  return expectedYears(survivalFrom(data, options, birthYear, 0, birthYear))
}

/** The grid length the statistics suggest: the age by which only about 1 in 10 people like you are still alive,
 * rounded up to a multiple of 5 so the fading tail fits, and always past today. */
export function suggestedGridYears(o: Outlook, min = 40, max = 120): number {
  const roundUp5 = (age: number) => Math.ceil(age / 5) * 5
  return Math.min(max, Math.max(min, roundUp5(ageAtChance(o, 0.1)), roundUp5(o.fromAge + 1)))
}

const DAYS_PER_YEAR = 365.2425

export type LifeProgress = {
  /** Exact age as a share (0–1) of the average age at death for people like you. */
  fraction: number
  /** Average years still ahead. */
  yearsLeft: number
  /** The calendar year that average falls in. */
  expectedYear: number
}

/** How much of an average lifetime for people like you has been lived. An average for a group, never a forecast. */
export function lifeProgress(o: Outlook, birthDate: CalendarDate, today: CalendarDate): LifeProgress {
  const exactAge = daysBetween(birthDate, today) / DAYS_PER_YEAR
  const startOfBirthYear = { year: birthDate.year, month: 1, day: 1 }
  return {
    fraction: exactAge / o.lifeExpectancy,
    yearsLeft: o.lifeExpectancy - exactAge,
    expectedYear: Math.floor(birthDate.year + daysBetween(startOfBirthYear, birthDate) / DAYS_PER_YEAR + o.lifeExpectancy),
  }
}
